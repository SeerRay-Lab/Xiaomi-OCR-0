const LANGUAGE_KEY = "xiaomi_ocr_demo_language";
function initialLanguage() {
  const requested = new URLSearchParams(location.search).get("lang");
  let saved;
  try { saved = localStorage.getItem(LANGUAGE_KEY); } catch (_) {}
  const preferred = requested || saved || navigator.language || "en";
  return /^zh(?:-|$)/i.test(preferred) ? "zh" : "en";
}
let uiLanguage = initialLanguage();
function t(key, values = {}) {
  const template = uiLanguage === "en" ? (Object.hasOwn(I18N_EN, key) ? I18N_EN[key] : key) : key;
  return String(template).replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}
const uiBindings = new Map();
function uiText(element, render) {
  if (typeof element === "string") element = document.getElementById(element);
  uiBindings.set(element, render);
  element.textContent = render();
}
// Capture only known page copy, once, before app.js creates results or accepts uploads.
const staticBindings = [];
const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  if (node.parentElement.closest("script, style, textarea")) continue;
  const original = node.textContent, key = original.trim();
  if (Object.hasOwn(I18N_EN, key)) {
    staticBindings.push(() => {
      if (node.isConnected) node.textContent = original.replace(key, t(key));
    });
  }
}
for (const element of document.querySelectorAll("[aria-label], [title], [placeholder], [alt]")) {
  for (const attr of ["aria-label", "title", "placeholder", "alt"]) {
    const key = element.getAttribute(attr);
    if (key && Object.hasOwn(I18N_EN, key)) staticBindings.push(() => element.setAttribute(attr, t(key)));
  }
}
function applyLanguage(language, persist = false) {
  uiLanguage = language === "zh" ? "zh" : "en";
  document.documentElement.lang = uiLanguage === "zh" ? "zh-CN" : "en";
  for (const render of staticBindings) render();
  for (const [element, render] of uiBindings) {
    if (element.isConnected) element.textContent = render();
    else uiBindings.delete(element);
  }
  const button = document.getElementById("btnLanguage");
  button.textContent = uiLanguage === "zh" ? "English" : "中文";
  button.setAttribute("aria-label", uiLanguage === "zh" ? "Switch to English" : "切换为中文");
  button.lang = uiLanguage === "zh" ? "en" : "zh-CN";
  if (persist) {
    try { localStorage.setItem(LANGUAGE_KEY, uiLanguage); } catch (_) {}
    const url = new URL(location.href);
    url.searchParams.set("lang", uiLanguage);
    history.replaceState(null, "", url);
  }
  document.dispatchEvent(new Event("languagechange"));
}
document.getElementById("btnLanguage").onclick = () => applyLanguage(uiLanguage === "zh" ? "en" : "zh", true);
applyLanguage(uiLanguage);
